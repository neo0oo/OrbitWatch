CREATE TABLE satellites (
    norad_id INT NOT NULL PRIMARY KEY,
    name NVARCHAR(100) NOT NULL,
    added_at DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

CREATE TABLE tle_cache (
    norad_id INT NOT NULL PRIMARY KEY
        REFERENCES satellites(norad_id) ON DELETE CASCADE,
    line1 NVARCHAR(80) NOT NULL,
    line2 NVARCHAR(80) NOT NULL,
    fetched_at DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);
